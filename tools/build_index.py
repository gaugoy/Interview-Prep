#!/usr/bin/env python3
"""Generate the machine index of all interview questions.

Outputs (all generated — never edit by hand):
  index/catalog.json   one record per question (id, stack, file, n, title, level, anchor,
                       lines, asked, status, words, code_lines, related ids)
  index/INDEX.md       small human/agent-readable counts table
  AGENT_INDEX.md       the block between <!-- AUTO:COUNTS:START --> / END markers
  README.md            live blocks: contents table + counts, at-a-glance, question badge

Usage:
  python3 tools/build_index.py           # write outputs
  python3 tools/build_index.py --check   # exit 1 if outputs are stale (CI / pre-commit)
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

from catalog import ROOT, STACKS, load
from readme_gen import README, render_readme

INDEX_DIR = ROOT / "index"
CATALOG = INDEX_DIR / "catalog.json"
SUMMARY = INDEX_DIR / "INDEX.md"
AGENT_INDEX = ROOT / "AGENT_INDEX.md"
START, END = "<!-- AUTO:COUNTS:START -->", "<!-- AUTO:COUNTS:END -->"
THIN_WORDS = 45   # prose words below this = "thin" (likely code-only) answer


def render(questions):
    catalog = "[\n" + ",\n".join(json.dumps(q.to_json(), ensure_ascii=False) for q in questions) + "\n]\n"  # one record per line → small, diff-friendly

    per_file = defaultdict(list)
    for q in questions:
        per_file[(q.stack, q.file)].append(q)
    per_stack = Counter(q.stack for q in questions)

    rows = ["| Stack | File | Q | Easy/Med/Hard | Thin | Asked | Status |", "|---|---|---|---|---|---|---|"]
    for (stack, file), qs in per_file.items():
        lv = Counter(q.level for q in qs)
        thin = sum(q.words < THIN_WORDS for q in qs)
        asked = sum(q.asked for q in qs)
        status = "/".join(sorted({q.status for q in qs}))
        lvl = f"{lv['easy']}/{lv['medium']}/{lv['hard']}" if (lv['easy'] or lv['medium'] or lv['hard']) else "—"
        rows.append(f"| {stack} | `{file}` | {len(qs)} | {lvl} | {thin or ''} | {asked or ''} | {status} |")

    stack_rows = ["| Stack | Questions | Prompt |", "|---|---|---|"] + [
        f"| {s} | {per_stack[s]} | `{STACKS[s]['prompt']}` |" for s in STACKS if per_stack[s]
    ]
    total = len(questions)
    summary = (
        "# Index summary (generated by `tools/build_index.py` — do not edit)\n\n"
        f"**{total} questions.** Full records: `index/catalog.json`. Search: `python3 tools/find.py <words>`.\n"
        f"Thin = fewer than {THIN_WORDS} words of explanation outside code (candidates for a theory pass).\n\n"
        + "\n".join(stack_rows) + "\n\n" + "\n".join(rows) + "\n"
    )
    counts_block = (
        f"{START}\n_Generated by `tools/build_index.py` — do not edit by hand._\n\n"
        f"**{total} questions total.** " + " · ".join(f"{s}: {per_stack[s]}" for s in STACKS if per_stack[s])
        + f". Thin answers: {sum(q.words < THIN_WORDS for q in questions)}. Asked in interviews: {sum(q.asked for q in questions)}. "
        "Per-file table: [`index/INDEX.md`](./index/INDEX.md).\n" + END
    )
    return catalog, summary, counts_block


def updated_agent_index(text: str, block: str) -> str:
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        _, post = rest.split(END, 1)
        return pre + block + post
    marker = "## 1. Where things live"
    insert = f"## 0. Live counts\n\n{block}\n\n---\n\n"
    return text.replace(marker, insert + marker, 1) if marker in text else text + "\n" + insert


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()

    questions, _ = load()
    catalog, summary, block = render(questions)
    readme = render_readme(questions)
    ai_old = AGENT_INDEX.read_text(encoding="utf-8")
    ai_new = updated_agent_index(ai_old, block)
    targets = {CATALOG: catalog, SUMMARY: summary, AGENT_INDEX: ai_new}
    if readme is not None:
        targets[README] = readme          # deterministic now → part of --check too

    if args.check:
        stale = [p for p, content in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
        if stale:
            old_ids = {q["id"]: q["title"] for q in json.loads(CATALOG.read_text())} if CATALOG.exists() else {}
            new_ids = {q.id for q in questions}
            gone = [t for i, t in old_ids.items() if i not in new_ids]
            print("Index is stale — run: python3 tools/build_index.py", file=sys.stderr)
            for p in stale:
                print(f"  stale: {p.relative_to(ROOT)}", file=sys.stderr)
            if gone:
                print(f"  {len(gone)} question id(s) disappeared (title edited or question removed — viewer ticks for them reset):", file=sys.stderr)
                for t in gone[:10]:
                    print(f"    - {t}", file=sys.stderr)
            return 1
        print(f"Index up to date ({len(questions)} questions).")
        return 0

    INDEX_DIR.mkdir(exist_ok=True)
    for p, content in targets.items():
        if not p.exists() or p.read_text(encoding="utf-8") != content:
            p.write_text(content, encoding="utf-8")
    print(f"Indexed {len(questions)} questions → index/catalog.json, INDEX.md, AGENT_INDEX.md counts, README.md counts.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
